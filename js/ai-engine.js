function analyzeTongueImage(imageElement) {

    return new Promise((resolve) => {

        setTimeout(() => {

            const canvas = document.createElement('canvas');

            const ctx = canvas.getContext('2d');

            try {

                canvas.width = imageElement.naturalWidth || 300;

                canvas.height = imageElement.naturalHeight || 200;

                ctx.drawImage(imageElement, 0, 0);

                const imageData = ctx.getImageData(0, 0, canvas.width, canvas.height).data;

                const colorAnalysis = analyzeTongueColor(imageData);

                resolve(generateTongueAnalysisResult(colorAnalysis));

            } catch (e) {

                resolve(generateDefaultTongueResult());

            }

        }, 1500);

    });

}



function analyzeTongueColor(imageData) {

    let rTotal = 0, gTotal = 0, bTotal = 0, pixelCount = 0;

    const w = Math.min(200, Math.sqrt(imageData.length / 4) | 0);

    const startX = Math.floor(w * 0.25), startY = Math.floor(w * 0.3);

    for (let y = startY; y < Math.min(startY + w * 0.5, (imageData.length / 4 / w) | 0); y += 4) {

        for (let x = startX; x < Math.min(startX + w * 0.5, w); x += 4) {

            const idx = (y * w + x) * 4;

            if (idx < imageData.length - 3) { rTotal += imageData[idx]; gTotal += imageData[idx+1]; bTotal += imageData[idx+2]; pixelCount++; }

        }

    }

    return { avgR: Math.round(rTotal/pixelCount), avgG: Math.round(gTotal/pixelCount), avgB: Math.round(bTotal/pixelCount), sampleSize: pixelCount };

}



