function generateProfessionalReply(userMessage, history) {

    var msg = (userMessage || '').trim();

    if (!msg) return '请描述您的不适症状，我会根据您的情况为您提供专业的初步分析和建议。';



    _consultState.turnCount++;



    // 消息指纹（检测重复输入）

    var fingerprint = _hashStr(msg);

    var isRepeat = (fingerprint === _consultState.lastUserFingerprint);

    _consultState.lastUserFingerprint = fingerprint;



    // === 第一层：紧急症状识别（始终最高优先级） ===

    if (/胸痛.*?(呼吸困|大汗|濒死)|意识不清|晕厥|昏迷|呕血|柏油便|血尿剧烈|剧烈头痛.*?呕吐|想.*(死|自杀|结束)/.test(msg)) {

        return '🚨 **【重要提醒 — 请务必重视】**\n\n' +

            '您描述的症状提示可能存在需要紧急处理的情况。\n\n' +

            '**以下任意一种情况都建议立即拨打120或前往最近医院急诊：**\n' +

            '• 胸痛伴呼吸困难/大汗/濒死感 → 急性心梗可能\n' +

            '• 意识模糊或晕厥 → 低血糖/中风/心律失常可能\n' +

            '• 咯血或呕鲜血 → 上消化道出血/咯血\n' +

            '• 黑便如柏油状 → 上消化道出血\n' +

            '• 表达自杀想法 → 请立刻告诉信任的人或拨打心理援助热线\n\n' +

            '**请不要延误，尽早获得专业医疗救助是最安全的选择。**\n' +

            '如有家属或朋友在场，请告知他们陪同您就医。';

    }



    // === 第二层：特殊意图识别 ===

    if (/(药|吃药|服用|用药|药物|治疗|吃.*药)/.test(msg)) {

        return _generateMedicineConsultReply(msg);

    }

    if (/(复查|复诊|还要查|接下来|后续|随访)/.test(msg)) {

        return _generateFollowUpVisitReply();

    }

    if (/(饮食|吃什么|怎么吃|忌口|养生|锻炼|运动|作息|生活习惯)/.test(msg)) {

        return _generateLifestyleReply(msg);

    }

    if (/(没有|无|不清楚|不知道|忘记了|还好|一般般|没什么|你好|您好|在吗)/.test(msg) && _consultState.turnCount <= 1) {

        return _generateDefaultGreeting();

    }



    // === 第三层：核心症状分析（引擎主体） ===

    var matchedCategory = _matchCategory(msg);



    if (!matchedCategory || !DISEASE_KNOWLEDGE_BASE[matchedCategory]) {

        // 无法分类 → 给出通用引导

        return _generateUnhandledReply(msg);

    }



    // 更新当前分类

    if (!_consultState.category) {

        _consultState.category = matchedCategory;

        _consultState.chiefComplaint = extractSymptomKeyword(msg);

    }



    // 根据对话轮次决定回复策略

    if (_consultState.turnCount <= 1 || !_consultState.repliedTopics || _consultState.repliedTopics.length === 0) {

        // ★ 首次回复：完整的舌诊级专业分析

        return _buildFirstReply(msg, matchedCategory, extractSymptomKeyword(msg));

    } else if (isRepeat) {

        // ★ 重复输入：给不同的角度

        return _buildRepeatHandlerReply(matchedCategory);

    } else if (_consultState.turnCount >= 7) {

        // ★ 深度对话（≥7轮）：给出完整方案

        return _buildFinalPlanReply(matchedCategory);

    } else {

        // ★ 中间轮次（2-6轮）：差异化追问回复

        return _buildFollowUpReply(msg, matchedCategory, _consultState.turnCount);

    }

}



