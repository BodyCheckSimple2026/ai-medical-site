/** 简单字符串哈希（用于消息去重） */

function _hashStr(str) {

    var h = 0;

    str = (str || '').replace(/\s+/g, '');

    for (var i = 0; i < str.length; i++) { h = ((h << 5) - h) + str.charCodeAt(i); h |= 0; }

    return Math.abs(h).toString(36);

}



/** 提取用户消息中的所有症状关键词 */

function extractSymptomKeyword(msg) {

    var symptoms = [];

    for (var kw in SYMPTOM_KW_MAP) {

        if (msg.indexOf(kw) > -1) symptoms.push(kw);

    }

    return symptoms.length > 0 ? symptoms.slice(0, 5).join('、') : msg.substring(0, 20);

}



/** 匹配用户消息到最佳疾病分类 */

function _matchCategory(msg) {

    var bestCat = null, bestScore = 0;



    // 先遍历 DISEASE_KNOWLEDGE_BASE 的 keywords

    for (var cat in DISEASE_KNOWLEDGE_BASE) {

        var kb = DISEASE_KNOWLEDGE_BASE[cat];

        if (!kb || !kb.keywords) continue;

        var s = 0;

        for (var k = 0; k < kb.keywords.length; k++) {

            if (msg.indexOf(kb.keywords[k]) > -1) s += kb.keywords[k].length;

        }

        if (s > bestScore) { bestScore = s; bestCat = cat; }

    }



    // 再遍历 SYMPTOM_KW_MAP 作为补充

    if (!bestCat) {

        var catCounts = {};

        for (var kw in SYMPTOM_KW_MAP) {

            if (msg.indexOf(kw) > -1) {

                var c = SYMPTOM_KW_MAP[kw];

                catCounts[c] = (catCounts[c] || 0) + kw.length;

            }

        }

        for (var cc in catCounts) {

            if (catCounts[cc] > bestScore) { bestScore = catCounts[cc]; bestCat = cc; }

        }

    }



    return bestCat;

}



/** 选择一个还没问过的追问问题 */

function _selectNextQuestion(category) {

    var kb = DISEASE_KNOWLEDGE_BASE[category];

    if (!kb || !kb.followUpQuestions || kb.followUpQuestions.length === 0) {

        return '请问还有其他需要补充的情况吗？';

    }



    var available = [];

    for (var i = 0; i < kb.followUpQuestions.length; i++) {

        var fp = _hashStr(kb.followUpQuestions[i]);

        if (_consultState.askedQuestions.indexOf(fp) < 0) {

            available.push(kb.followUpQuestions[i]);

        }

    }



    if (available.length === 0) {

        // 所有问题都问过了，给一个开放性问题

        return '还有其他方面的信息想要补充吗？或者我们可以开始讨论调理方案。';

    }



    return available[Math.floor(Math.random() * available.length)];

}



