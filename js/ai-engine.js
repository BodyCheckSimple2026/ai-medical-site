                    var v=+(midValue - range*(0.06+Math.random()*0.22)).toFixed(getDecimalPlaces(unit));

                    value=isFinite(v)&&!isNaN(v)?v:+(midValue-range*0.08).toFixed(getDecimalPlaces(unit));

